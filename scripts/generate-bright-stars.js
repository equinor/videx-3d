/**
 * Extracts the stars to magnitude 5 from the Yale Bright Star Catalogue, 5th revised
 * edition (Hoffleit & Warren 1991, CDS catalogue V/50), into
 * src/sdk/utils/bright-stars-data.ts.
 *
 *   node scripts/generate-bright-stars.js [path/to/catalog(.gz)]
 *
 * Without a path it downloads the catalogue from CDS. Each star is packed in 6 bytes,
 * little-endian: right ascension (uint16, a full turn), declination (int16, ±90°),
 * visual magnitude (uint8, (V + 2) * 30) and B-V (int8, * 60), all for J2000.
 */

import fs from 'node:fs';
import { gunzipSync } from 'node:zlib';

const SOURCE = 'https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz';
const OUTPUT = 'src/sdk/utils/bright-stars-data.ts';
const MAGNITUDE_LIMIT = 5;
// Sun-like, for the few stars without a colour.
const DEFAULT_COLOR_INDEX = 0.6;

async function readCatalogue(path) {
  const raw = path
    ? fs.readFileSync(path)
    : Buffer.from(await (await fetch(SOURCE)).arrayBuffer());
  return (raw[0] === 0x1f && raw[1] === 0x8b ? gunzipSync(raw) : raw).toString(
    'latin1',
  );
}

// Columns are 1-based and inclusive, as in the catalogue's ReadMe.
const field = (line, from, to) => line.slice(from - 1, to).trim();
const number = (line, from, to) => {
  const text = field(line, from, to);
  return text === '' ? NaN : Number(text);
};

function parse(text) {
  const stars = [];
  for (const line of text.split('\n')) {
    const magnitude = number(line, 103, 107);
    const raHours = number(line, 76, 77);
    // Novae and other objects kept only for their numbers have no position.
    if (!(magnitude <= MAGNITUDE_LIMIT) || !Number.isFinite(raHours)) continue;
    const rightAscension =
      (raHours + number(line, 78, 79) / 60 + number(line, 80, 83) / 3600) * 15;
    const sign = field(line, 84, 84) === '-' ? -1 : 1;
    const declination =
      sign *
      (number(line, 85, 86) +
        number(line, 87, 88) / 60 +
        number(line, 89, 90) / 3600);
    const colorIndex = number(line, 110, 114);
    stars.push({
      rightAscension,
      declination,
      magnitude,
      colorIndex: Number.isFinite(colorIndex)
        ? colorIndex
        : DEFAULT_COLOR_INDEX,
    });
  }
  // Brightest first.
  return stars.sort((a, b) => a.magnitude - b.magnitude);
}

function pack(stars) {
  const view = new DataView(new ArrayBuffer(stars.length * 6));
  stars.forEach((star, i) => {
    const at = i * 6;
    view.setUint16(
      at,
      Math.round((star.rightAscension / 360) * 65536) % 65536,
      true,
    );
    view.setInt16(at + 2, Math.round((star.declination / 90) * 32767), true);
    view.setUint8(at + 4, Math.round((star.magnitude + 2) * 30));
    view.setInt8(
      at + 5,
      Math.round(Math.min(Math.max(star.colorIndex, -0.5), 2.1) * 60),
    );
  });
  return Buffer.from(view.buffer).toString('base64');
}

const stars = parse(await readCatalogue(process.argv[2]));
fs.writeFileSync(
  OUTPUT,
  `// Generated by scripts/generate-bright-stars.js: do not edit.
// The Yale Bright Star Catalogue, 5th revised edition (Hoffleit & Warren 1991, CDS V/50),
// to magnitude ${MAGNITUDE_LIMIT}, for J2000; packed as the script describes.

export const BRIGHT_STAR_COUNT = ${stars.length};

export const BRIGHT_STAR_DATA =
  '${pack(stars)}';
`,
);
console.log(
  `${stars.length} stars to magnitude ${MAGNITUDE_LIMIT} -> ${OUTPUT}`,
);
